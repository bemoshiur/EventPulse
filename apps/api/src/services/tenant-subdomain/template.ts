/**
 * Nginx vhost template for tenant subdomains — Sprint 3 Day 22 Workstream 2.
 *
 * Per Decision O.1 (decisions.md 2026-05-19), the staging cert is wildcard
 * `*.staging.eventpulse.com.bd` and the Route 53 wildcard A record routes
 * any `<slug>.staging.eventpulse.com.bd` to the staging EIP. Tenant
 * subdomain provisioning is therefore PURE-NGINX — generate a vhost file,
 * symlink it into sites-enabled, run nginx -t + reload. No certbot in the
 * per-tenant hot path.
 *
 * The vhost shape mirrors the production target §17.4 vhost template:
 *   - listen 443 ssl http2 + listen [::]:443
 *   - TLS termination via the wildcard cert (shared file paths with the
 *     existing 5 enumerated vhosts)
 *   - security headers snippet include
 *   - per-tenant /nginx-health Nginx-direct liveness probe (matches the
 *     Sprint 2 Day 16 silent-failure remediation pattern)
 *   - / proxied to the Next.js public route group at 127.0.0.1:3000 with
 *     X-Tenant-Slug header so apps/web middleware can route to the right
 *     tenant context without parsing Host (defense in depth)
 *   - long-cache /_next/static/ proxied through
 *
 * Slug validation lives in the caller; this module assumes the slug has
 * already been validated against the same regex tenants.slug allows
 * (`^[a-z0-9][a-z0-9-]*[a-z0-9]$`, 3-30 chars, reserved-handles blocked).
 *
 * Returns the full vhost file content as a string. The provisioner
 * SSM-writes this string to /etc/nginx/sites-available/<slug>.conf on
 * the EC2.
 */

export interface VhostTemplateVars {
  /** Tenant slug — validated by caller; embedded verbatim into server_name + comments. */
  slug: string
  /** Apex of the env (e.g. 'staging.eventpulse.com.bd' or 'eventpulse.com.bd' in prod). */
  apexDomain: string
  /** Path to the cert lineage — defaults to the env's standard path. */
  certLineagePath?: string
}

/**
 * Defence-in-depth slug check at template generation time. The caller's
 * tenants.slug CHECK + reserved-handles guard should have already
 * rejected anything bad; this catches the edge case where the caller
 * forgot to validate before calling the template generator. A bad slug
 * here would write a vhost with shell-special characters into Nginx
 * config — catastrophic if a future caller passes user input directly.
 */
const SLUG_REGEX = /^[a-z0-9][a-z0-9-]{1,28}[a-z0-9]$/

export class InvalidTenantSlugError extends Error {
  constructor(slug: string) {
    super(
      `Invalid tenant slug for vhost template: ${JSON.stringify(slug)}. ` +
        `Must match ${SLUG_REGEX.source} (3-30 chars, lowercase alphanumeric + hyphens).`,
    )
    this.name = 'InvalidTenantSlugError'
  }
}

export function renderTenantVhost(vars: VhostTemplateVars): string {
  if (!SLUG_REGEX.test(vars.slug)) {
    throw new InvalidTenantSlugError(vars.slug)
  }
  const hostname = `${vars.slug}.${vars.apexDomain}`
  const certPath = vars.certLineagePath ?? `/etc/letsencrypt/live/${vars.apexDomain}`

  return `# Tenant vhost — ${vars.slug} · ${vars.apexDomain}
# Generated by apps/api/src/services/tenant-subdomain/provision.ts on
# the first successful KYC approve transition (Item 13).
#
# Decision O.1: wildcard cert + wildcard A record live; this vhost
# does NOT require certbot. The cert at ${certPath}/fullchain.pem
# covers ${hostname} via the *.${vars.apexDomain} SAN.
#
# To regenerate: trigger another KYC approve transition for this tenant
# (idempotent; tenants.subdomain_provisioned_at unchanged on re-runs).

server {
  listen 443 ssl http2;
  listen [::]:443 ssl http2;
  server_name ${hostname};

  ssl_certificate     ${certPath}/fullchain.pem;
  ssl_certificate_key ${certPath}/privkey.pem;
  ssl_protocols       TLSv1.2 TLSv1.3;
  ssl_prefer_server_ciphers off;
  ssl_session_cache   shared:SSL:10m;
  ssl_session_timeout 1d;

  include /etc/nginx/snippets/ep-security-headers.conf;

  # Nginx-direct liveness probe per Sprint 2 silent-failure remediation
  # (PR #116). Distinguishes nginx-up-tenant-down from nginx-down.
  location = /nginx-health {
    add_header Content-Type text/plain;
    return 200 "ok\\n";
  }

  # Next.js static assets — long-cache aggressively.
  location /_next/static/ {
    proxy_pass http://127.0.0.1:3000;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    expires 1y;
    add_header Cache-Control "public, immutable";
  }

  location / {
    proxy_pass http://127.0.0.1:3000;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    # Defense in depth: pass the tenant slug as an explicit header so
    # apps/web middleware doesn't have to re-parse Host. The middleware
    # cross-checks this against the Host header.
    proxy_set_header X-Tenant-Slug ${vars.slug};
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_read_timeout 60s;
  }
}
`
}

/**
 * Build the SSM SendCommand parameter list for provisioning a vhost.
 * Splits the file content via base64 to avoid quote-escaping nightmares
 * when interpolating into the shell command — the EC2-side script
 * base64-decodes back into the destination file.
 *
 * Returns the list of shell commands the SSM document will execute,
 * in order. Each must succeed or the chain aborts; the rollback path
 * is handled in provision.ts by inspecting the SSM CommandInvocation
 * status.
 */
export function buildProvisionCommands(vars: { slug: string; vhostContent: string }): string[] {
  if (!SLUG_REGEX.test(vars.slug)) {
    throw new InvalidTenantSlugError(vars.slug)
  }
  const dst = `/etc/nginx/sites-available/${vars.slug}.conf`
  const lnk = `/etc/nginx/sites-enabled/${vars.slug}.conf`
  const base64 = Buffer.from(vars.vhostContent, 'utf-8').toString('base64')

  return [
    // Idempotency check: if the symlink already exists AND points at the
    // expected sites-available path, exit success with a no-op marker.
    // The provisioner reads SSM output for the marker to know it didn't
    // actually do work.
    `if [ -L ${lnk} ] && [ "$(readlink ${lnk})" = "${dst}" ] && [ -f ${dst} ]; then echo PROVISION_NO_OP_ALREADY_EXISTS; exit 0; fi`,
    // Write the vhost content via base64 to avoid shell-escape risks
    // on the (validated) slug appearing in server_name.
    `echo '${base64}' | base64 -d | sudo tee ${dst} > /dev/null`,
    // Symlink into sites-enabled.
    `sudo ln -sf ${dst} ${lnk}`,
    // Validate config — if this fails the next command (reload) is
    // skipped because '&&' short-circuits, AND the rollback path
    // (file delete) runs in the cleanup.
    `if ! sudo nginx -t 2>&1; then echo PROVISION_FAILED_NGINX_T; sudo rm -f ${lnk} ${dst}; exit 1; fi`,
    // Reload Nginx — at this point config is valid; reload swaps worker
    // processes gracefully.
    `sudo systemctl reload nginx && echo PROVISION_OK`,
  ]
}

/**
 * Build the SSM commands for removing a tenant vhost (rollback or
 * tenant termination cleanup). Idempotent: missing files / symlinks
 * don't error.
 */
export function buildTeardownCommands(vars: { slug: string }): string[] {
  if (!SLUG_REGEX.test(vars.slug)) {
    throw new InvalidTenantSlugError(vars.slug)
  }
  const dst = `/etc/nginx/sites-available/${vars.slug}.conf`
  const lnk = `/etc/nginx/sites-enabled/${vars.slug}.conf`
  return [
    `sudo rm -f ${lnk} ${dst}`,
    `sudo nginx -t && sudo systemctl reload nginx && echo TEARDOWN_OK`,
  ]
}
